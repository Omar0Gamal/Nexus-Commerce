-- name: DecrementProductStock :one
-- Atomically decrements stock only when sufficient units are available.
-- Returns the updated row; returns no rows when stock is insufficient.
UPDATE products
SET stock_quantity = stock_quantity - $3
WHERE id = $1
  AND shop_id = $2
  AND track_inventory = TRUE
  AND stock_quantity >= $3
RETURNING id, stock_quantity, low_stock_threshold;

