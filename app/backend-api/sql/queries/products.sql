-- name: SearchProductsFTS :many
SELECT
    p.id, p.shop_id, p.category_id, p.title, p.slug, p.description, p.price,
    p.compare_at_price, p.track_inventory, p.stock_quantity, p.low_stock_threshold,
    p.sku, p.status, p.seo_title, p.seo_description, p.created_at, p.deleted_at,
    ts_rank(p.search_vector, plainto_tsquery('english', @query::text)) AS rank
FROM products p
WHERE p.shop_id = @shop_id
  AND p.deleted_at IS NULL
  AND (
      p.search_vector @@ plainto_tsquery('english', @query::text)
      OR similarity(p.title, @query::text) > 0.2
  )
  AND (@min_price::numeric IS NULL OR p.price >= @min_price)
  AND (@max_price::numeric IS NULL OR p.price <= @max_price)
  AND (@category_id = '00000000-0000-0000-0000-000000000000'::uuid OR p.category_id = @category_id)
ORDER BY rank DESC, p.title
LIMIT @lim OFFSET @off;

-- name: GetSearchFacets :many
SELECT key, value, COUNT(*)::int AS count
FROM product_attributes
WHERE shop_id = @shop_id
GROUP BY key, value
ORDER BY key, count DESC;

-- name: GetPopularFilters :many
SELECT key, COUNT(DISTINCT value)::int AS distinct_values
FROM product_attributes
WHERE shop_id = @shop_id
GROUP BY key
ORDER BY distinct_values DESC
LIMIT 20;
