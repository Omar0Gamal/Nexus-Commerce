-- name: SearchProducts :many
-- Full-text trigram search. Results ordered by similarity descending.
-- AI seam: this query will be replaced by a pgvector cosine similarity search
--          once product embeddings are generated by the AI Engine.
SELECT id, shop_id, category_id, title, slug, description, price,
       compare_at_price, track_inventory, stock_quantity, low_stock_threshold,
       sku, status, seo_title, seo_description, created_at, deleted_at,
       similarity(title, @query::text) AS title_sim
FROM products
WHERE shop_id = @shop_id
  AND deleted_at IS NULL
  AND (title % @query::text OR description % @query::text)
ORDER BY title_sim DESC
LIMIT @max_results::int;

-- name: GetCopurchasedProducts :many
SELECT oi2.product_id, COUNT(*) AS co_count
FROM order_items oi1
JOIN order_items oi2 ON oi1.order_id = oi2.order_id
JOIN orders o ON o.id = oi1.order_id
WHERE o.shop_id = @shop_id
  AND oi1.product_id = @product_id
  AND oi2.product_id != @product_id
  AND o.status = 'completed'
GROUP BY oi2.product_id
ORDER BY co_count DESC
LIMIT @max_results::int;

